// Builds seed.sql (starter content) and setup.sql (everything in one file for
// the Supabase SQL Editor) from supabase/migrations and content/*.json.

import { createHash } from "node:crypto";
import { readFileSync, readdirSync } from "node:fs";
import path from "node:path";
import { buildHints, type WordHint } from "../lib/words";

const root = path.resolve(__dirname, "..");

type SentenceIn = { en: string; ar: string };
type QuestionIn = { en: string; ar: string; options: string[]; answer: number };
type WordIn = { word: string; ar: string; example_en?: string; example_ar?: string };
type UnitIn = {
  slug: string;
  title_en: string;
  title_ar: string;
  description_en?: string;
  description_ar?: string;
  level: string;
  theme: string;
  emoji: string;
  glossary?: Record<string, string>;
  sentences?: SentenceIn[];
  questions?: QuestionIn[];
  words?: WordIn[];
};

/** Stable UUID from a name, so re-running the seed never duplicates rows. */
export function uuidFrom(name: string): string {
  const h = createHash("sha1").update(`jumla:${name}`).digest();
  h[6] = (h[6] & 0x0f) | 0x50;
  h[8] = (h[8] & 0x3f) | 0x80;
  const hex = h.subarray(0, 16).toString("hex");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20, 32)}`;
}

const q = (s: string | null | undefined) => (s == null ? "null" : `'${s.replace(/'/g, "''")}'`);
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

function readJson<T>(file: string): T {
  return JSON.parse(readFileSync(path.join(root, "content", file), "utf8")) as T;
}

function unitSql(type: string, u: UnitIn, order: number, glossary: Record<string, string>): string[] {
  const id = uuidFrom(`unit:${u.slug}`);
  const out = [
    `insert into public.units (id, type, slug, title_en, title_ar, description_en, description_ar, level, theme, emoji, sort_order)
values (${q(id)}, ${q(type)}, ${q(u.slug)}, ${q(u.title_en)}, ${q(u.title_ar)}, ${q(u.description_en ?? "")}, ${q(u.description_ar ?? "")}, ${q(u.level)}, ${q(u.theme)}, ${q(u.emoji)}, ${order})
on conflict do nothing;`,
  ];
  const g = { ...glossary, ...(u.glossary ?? {}) };
  (u.sentences ?? []).forEach((s, i) => {
    const hints: WordHint[] = buildHints(s.en, g);
    out.push(
      `insert into public.sentences (id, unit_id, position, text_en, text_ar, word_hints) values (${q(uuidFrom(`sentence:${u.slug}:${i}`))}, ${q(id)}, ${i}, ${q(s.en)}, ${q(s.ar)}, ${j(hints)}) on conflict do nothing;`,
    );
  });
  (u.questions ?? []).forEach((x, i) => {
    out.push(
      `insert into public.questions (id, unit_id, position, prompt_en, prompt_ar, options, correct_index) values (${q(uuidFrom(`question:${u.slug}:${i}`))}, ${q(id)}, ${i}, ${q(x.en)}, ${q(x.ar)}, ${j(x.options)}, ${x.answer}) on conflict do nothing;`,
    );
  });
  (u.words ?? []).forEach((w, i) => {
    out.push(
      `insert into public.words (id, unit_id, position, word, translation_ar, example_en, example_ar) values (${q(uuidFrom(`word:${u.slug}:${i}`))}, ${q(id)}, ${i}, ${q(w.word)}, ${q(w.ar)}, ${q(w.example_en ?? "")}, ${q(w.example_ar ?? "")}) on conflict do nothing;`,
    );
  });
  return out;
}

/** Starter content. Uses ON CONFLICT DO NOTHING, so it never overwrites admin edits. */
export function buildSeedSql(): string {
  const glossary = readJson<Record<string, string>>("glossary.json");
  const lines = ["-- Generated by `npm run sql:build` from content/*.json. Safe to run again.", "begin;"];
  readJson<UnitIn[]>("stories.json").forEach((u, i) => lines.push(...unitSql("story", u, i, glossary)));
  readJson<UnitIn[]>("passages.json").forEach((u, i) => lines.push(...unitSql("passage", u, i, glossary)));
  readJson<UnitIn[]>("wordlists.json").forEach((u, i) => lines.push(...unitSql("word_list", u, i, glossary)));
  lines.push("commit;", "");
  return lines.join("\n");
}

export function migrationFiles(): { name: string; sql: string }[] {
  const dir = path.join(root, "supabase", "migrations");
  return readdirSync(dir)
    .filter((f) => f.endsWith(".sql"))
    .sort()
    .map((name) => ({ name, sql: readFileSync(path.join(dir, name), "utf8") }));
}

export function buildSetupSql(): string {
  const parts = [
    "-- Jumla: full setup for the Supabase SQL Editor (Generated by `npm run sql:build`).",
    "-- 1) غيّر الإيميل وكود الدعوة في القسم المعلَّم بـ ✏️ تحت.  2) اضغط Run.",
    "-- Safe to run again: it creates what is missing and never deletes data.",
    "",
    ...migrationFiles().map((m) => `-- ===== ${m.name} =====\n${m.sql}`),
    "-- ===== ✏️ Settings: edit these two values before running =====",
    "update public.app_settings set value = 'you@example.com' where key = 'admin_emails' and value = '';",
    "update public.app_settings set value = 'change-me' where key = 'invite_code' and value = '';",
    "update public.profiles set role = 'admin'",
    "  where id in (select id from auth.users where public.is_admin_email(email));",
    "",
    "-- ===== Starter content =====",
    buildSeedSql(),
  ];
  return parts.join("\n");
}
